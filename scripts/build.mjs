import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { buildPalettes } from '../src/palettes.mjs';
import vm from 'node:vm';
import { createHash } from 'node:crypto';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = async file => (await readFile(resolve(root, file), 'utf8')).replace(/\r\n/g, '\n');
const pkg = JSON.parse(await read('package.json'));
let accountClientVersion = pkg.version;
try {
  const hostAccount = resolve(process.env.DSH_APP_DIR ?? 'C:/Program Files/dsh-esktop/DSH Desktop/resources/app', 'node_modules/@deepseek-ai/dsh-client-ui-settings-account/package.json');
  accountClientVersion = JSON.parse(await readFile(hostAccount, 'utf8')).version;
} catch { /* Portable builds identify their actual plugin version. */ }
const palette = JSON.parse(await read('src/palette.json'));
const extra = JSON.parse(await read('src/palette-extra.json'));
const styles = [];
// Inline the OFL fonts so plugin loading does not depend on user font registration
// or a remote CDN. Font licenses ship alongside the generated client.
const faces = [
  ['JetBrains Mono', 'JetBrainsMono-Regular.ttf', 400],
  ['JetBrains Mono', 'JetBrainsMono-Bold.ttf', 700],
  ['Rajdhani', 'Rajdhani-Regular.ttf', 400],
  ['Rajdhani', 'Rajdhani-SemiBold.ttf', 600],
  ['Rajdhani', 'Rajdhani-Bold.ttf', 700],
];
const fontCSS = [];
const harmonyFaces = [
  ['regular', 'Regular', '297b088424be212207df2ce8b98e335468b782aa6b96832af0b8b773d711e2b1'],
  ['medium', 'Medium', '6ed1553edccddc48eb27ff25d134a4a715cf54211238d4840b3038576cba1944'],
  ['bold', 'Bold', '43a424b85e47fb53a17b3b32026a71801f86f8e022ca6798d186b47d39fa5f01'],
];
for (const [key, weightName, sha256] of harmonyFaces) {
  const bytes = await readFile(resolve(root, `assets/fonts/HarmonyOS_Sans_SC_${weightName}.ttf`));
  if (createHash('sha256').update(bytes).digest('hex') !== sha256) throw new Error(`HarmonyOS ${weightName} must remain the original unmodified TTF.`);
  const chunk = `client.harmony-${key}.js`;
  const output = `// Original HarmonyOS Sans SC. Copyright 2021 Huawei Device Co., Ltd.\n// See assets/fonts/HarmonyOS-Sans-LICENSE.txt. Font bytes are unmodified.\nwindow.__ModuleLoader__.load({id:"@local/dsh-550-aic-theme",chunk:${JSON.stringify(chunk)},factory:()=>({source:${JSON.stringify(`url(data:font/ttf;base64,${bytes.toString('base64')}) format("truetype")`)}})});\n`;
  new vm.Script(output, {filename:chunk});
  if (process.argv.includes('--check')) {
    if (await read(chunk) !== output) throw new Error(`${chunk} is stale. Run npm run build.`);
  } else await writeFile(resolve(root, chunk), output);
}
for (const [family, file, weight] of faces) {
  const encoded = (await readFile(resolve(root, 'assets/fonts', file))).toString('base64');
  fontCSS.push(`@font-face{font-family:"${family}";font-style:normal;font-weight:${weight};font-display:swap;src:url(data:font/ttf;base64,${encoded}) format("truetype");}`);
}
styles.push({name:'bundled-fonts',css:fontCSS.join('\n')});
for (const file of (await readdir(resolve(root, 'src/styles'))).filter(f => f.endsWith('.css')).sort()) {
  styles.push({ name: file.replace('.css', ''), css: await read(`src/styles/${file}`) });
}
const locales = Object.fromEntries(await Promise.all(['zh', 'en'].map(async lang => [lang, JSON.parse(await read(`locale/${lang}.json`)).ui])));
const accountSource = await read('src/account.js');
const heroDotfieldSource = `${await read('src/hero-dotfield-gpu.js')}\n${await read('src/hero-dotfield.js')}`;
const composerStripSource = await read('src/composer-strip.js');
const harmonyFontSource = await read('src/harmony-fonts.js');
const source = (await read('src/client.js'))
  .replace('/* @palette */', () => JSON.stringify({ ...palette, ...extra }, null, 2))
  .replace('/* @schemes */', () => JSON.stringify(buildPalettes({ ...palette, ...extra }), null, 2))
  .replace('/* @styles */', () => JSON.stringify(styles, null, 2))
  .replace('/* @locales */', () => JSON.stringify(locales, null, 2))
  .replace('/* @account */', () => accountSource)
  .replace('/* @hero-dotfield */', () => heroDotfieldSource)
  .replace('/* @composer-strip */', () => composerStripSource)
  .replace('/* @harmony-fonts */', () => harmonyFontSource)
  .replace('/* @account-client-version */', () => JSON.stringify(accountClientVersion));
const output = '// Generated by npm run build. Edit src/, not this file.\n' + source;
new vm.Script(output, { filename: 'client.js' });
if (process.argv.includes('--check')) {
  if (await read('client.js') !== output) throw new Error('client.js is stale. Run npm run build.');
  console.log('Generated client is current.');
} else {
  await writeFile(resolve(root, 'client.js'), output);
  console.log(`Built client.js: ${Object.keys({ ...palette, ...extra }).length} tokens, ${styles.length} stylesheets.`);
}
